"""Dimension-reduction matrix: the projection must ACTUALLY shrink blocks.

Companion to test_lane_exploitation_matrix.py. That file pins WHICH
exploitation engages per lane; this file pins that the engine really works
in blocks of the theoretically reduced dimension -- correctness alone can
hide a lane that quietly solves the big block and relabels it.

The oracle is INDEPENDENT: Burnside orbit counting implemented here from
scratch (fixed-point counts of the group action on bitstrings, character-
weighted), never the engine's own tables. Per symmetry content:

  U(1) Sz            dim = C(N, n_up)
  + abelian k        dim_k = (1/|A|) sum_a chi_k(a)* fix(a)
  + flip at N/2      dim_(k,+/-) = (1/2)[dim_k +/- (1/|A|) sum_a chi_k(a)* fix(aF)]
  + little group     m_sigma per (k, sigma), sum_sigma m_sigma d_sigma = dim_k
  TR / star folds    dims UNCHANGED (folds reduce #solves, never block size)

Engine-side "actual dims" observables (never trusted, always compared):
  * lane B: SectorTag.sector_dim -- the dim of the operator Lanczos ran on
    (tag dims are structural; lane B's unguarded excited VALUES, GAP 10,
    do not matter here)
  * lane A: star plan dim_k0, and the per-block label arrays of
    little_group_full_spectrum -- rows per (k_raw, flip, irrep) = m_sigma,
    the dim of the isotypic block actually diagonalised
  * thermal: per_sector sector_dim across every (n_up, k[, +/-]) block

Matvec regimes: the reduced-CSR sub-mode is the default; the CSR-free
gather walk is forced two ways --
  * in-process via ED_SYM_SECTOR_CSR_BUDGET_GIB (read PER CALL: a tiny
    budget makes every sector decline the CSR and fall back), and
  * end-to-end via ED_SYM_REDUCED_CSR=0 in a SUBPROCESS (that knob is
    resolved once per process, so an in-process monkeypatch after first
    use would silently test nothing).
Both must produce identical dims AND identical physics.
"""
from __future__ import annotations

import itertools
import json
import math
import os
import subprocess
import sys
from collections import Counter

import numpy as np
import pytest

qed = pytest.importorskip("qed")
pytest.importorskip("pynauty")
from qed import _core  # noqa: E402
from qed.point_group_routing import resolve_projection_lane  # noqa: E402

N = 8


# ---------------------------------------------------------------------------
# Models
# ---------------------------------------------------------------------------

def _ring_bonds(n=N):
    return [(i, (i + 1) % n) for i in range(n)]


def _torus_bonds():
    """2x4 torus: horizontal wrap on 4 columns, one vertical bond per
    column (2 rows). Gives a 2-generator abelian translation group."""
    bonds = []
    for r in range(2):
        for c in range(4):
            bonds.append((r * 4 + c, r * 4 + (c + 1) % 4))
    for c in range(4):
        bonds.append((c, 4 + c))
    return bonds


def _op(bonds, n=N):
    b = qed.input.HamiltonianBuilder(n)
    b.heisenberg(bonds, J=1.0)
    return b.to_operator()


def _dense(bonds, n=N):
    dim = 1 << n
    H = np.zeros((dim, dim))
    sz = lambda s, i: 0.5 if (s >> i) & 1 else -0.5  # noqa: E731
    for s in range(dim):
        for i, j in bonds:
            H[s, s] += sz(s, i) * sz(s, j)
            if ((s >> i) & 1) != ((s >> j) & 1):
                H[s ^ (1 << i) ^ (1 << j), s] += 0.5
    return H


# ---------------------------------------------------------------------------
# The independent Burnside oracle
# ---------------------------------------------------------------------------

def _perm_apply(s: int, p: list[int]) -> int:
    t = 0
    for i, pi in enumerate(p):
        if (s >> pi) & 1:
            t |= 1 << i
    return t


def _compose(p, q):  # (p*q)(i) = p[q[i]]
    return [p[qi] for qi in q]


def _close(gens, n):
    ident = list(range(n))
    elems = {tuple(ident)}
    frontier = [ident]
    while frontier:
        nxt = []
        for e in frontier:
            for g in gens:
                c = tuple(_compose(g, e))
                if c not in elems:
                    elems.add(c)
                    nxt.append(list(c))
        frontier = nxt
    return [list(e) for e in sorted(elems)]


def _burnside_dims(n, n_up, generators, orders, flip: bool):
    """Multiset of irrep-block dims of the fixed-Sz subspace under the
    abelian group generated by `generators` (optionally x Z2 flip).
    Requires independent generators (|closure| == prod(orders)); the
    caller skips otherwise -- dependent generators would need Smith
    normal form to enumerate characters, and the audit showed the C++
    minimal generators are NOT always independent."""
    A = _close(generators, n)
    if len(A) != int(np.prod(orders)):
        pytest.skip("generators are not independent; character "
                    "enumeration by exponent tuple would be wrong")
    states = [s for s in range(1 << n) if bin(s).count("1") == n_up]
    # element list with exponent tuples, in the same order
    elems = []
    for exps in itertools.product(*[range(o) for o in orders]):
        e = list(range(n))
        for g, k in zip(generators, exps):
            for _ in range(k):
                e = _compose(g, e)
        elems.append((exps, e))
    mask = (1 << n) - 1
    fix_plain = {tuple(x): sum(1 for s in states if _perm_apply(s, e) == s)
                 for x, e in elems}
    if flip:
        fix_flip = {tuple(x): sum(1 for s in states
                                  if _perm_apply(s ^ mask, e) == s)
                    for x, e in elems}
    dims = []
    for qs in itertools.product(*[range(o) for o in orders]):
        acc_p = acc_f = 0.0
        for exps, _e in elems:
            chi = np.prod([np.exp(-2j * np.pi * q * k / o)
                           for q, k, o in zip(qs, exps, orders)])
            acc_p += (np.conj(chi) * fix_plain[tuple(exps)]).real
            if flip:
                acc_f += (np.conj(chi) * fix_flip[tuple(exps)]).real
        if not flip:
            d = acc_p / len(elems)
            dims.append(round(d))
        else:
            for s in (+1, -1):
                d = (acc_p + s * acc_f) / (2 * len(elems))
                dims.append(round(d))
    dims = [d for d in dims if d > 0]
    assert sum(dims) == math.comb(n, n_up), "oracle covering failed"
    return Counter(dims)


